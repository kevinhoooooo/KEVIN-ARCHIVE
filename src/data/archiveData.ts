const ROMAN_STUDIES = ['I', 'II', 'III', 'IV', 'V', 'VI'];

export const ARCHIVE_DATA: Record<ArchiveYear, FilmRoll[]> = YEAR_CONFIGS.reduce(
  (acc, cfg) => {
    const year = cfg.year;
    const seeds = ROLL_SEEDS[year];

    acc[year] = seeds.map((seed, rIdx) => {
      const rollNum = rIdx + 1;
      const rollCode = `FILM ${String(rollNum).padStart(2, '0')}`;
      const frameCount = seed.frameCount ?? seed.frameTitles.length;
      const frames: PhotoFrame[] = Array.from({ length: frameCount }, (_, fIdx) => {
        const frameNum = fIdx + 1;
        const frameCode = `${String(frameNum).padStart(2, '0')}A`;
        const imgUrl = seed.images[fIdx % seed.images.length];
        const baseTitle = seed.frameTitles[fIdx % seed.frameTitles.length];
        const cycle = Math.floor(fIdx / seed.frameTitles.length);
        const title = cycle > 0 ? `${baseTitle} · ${ROMAN_STUDIES[cycle % ROMAN_STUDIES.length]}` : baseTitle;
        const day = 1 + ((fIdx * 2 + rIdx) % 28);
        return {
          id: `${year}-R${rollNum}-F${frameNum}`,
          frameNumber: frameNum,
          frameCode,
          title,
          location: seed.location,
          date: `${year} · ${seed.month} ${String(day).padStart(2, '0')}`,
          camera: seed.camera,
          lens: seed.lens,
          filmStock: cfg.filmStock,
          exposure: fIdx % 2 === 0 ? 'f/5.6 · 1/250s' : 'f/4 · 1/125s',
          notes: seed.notes[fIdx % seed.notes.length],
          imageUrl: imgUrl,
          cropFocus: CROP_PRESETS[(fIdx + rIdx) % CROP_PRESETS.length],
        };
      });

      return {
        id: `${year}-roll-${rollNum}`,
        year,
        rollNumber: rollNum,
        rollCode,
        title: seed.title,
        filmStock: cfg.filmStock,
        iso: cfg.iso,
        location: seed.location,
        month: seed.month,
        frames,
      };
    });

    return acc;
  },
  {} as Record<ArchiveYear, FilmRoll[]>
);

