export type ArchiveYear =
  | '2026'
  | '2025'
  | '2024'
  | '2023'
  | '2022'
  | '2021'
  | '2020'
  | '2019';

export interface YearConfig {
  year: ArchiveYear;
  label: string;
  color: string;
  tintHex: number;
  filmStock: string;
  iso: number;
  seriesTheme: string;
  cabinetX: number;
}

export interface PhotoFrame {
  id: string;
  frameNumber: number;
  frameCode: string;
  title: string;
  location: string;
  date: string;
  camera: string;
  lens: string;
  filmStock: string;
  exposure: string;
  notes: string;
  imageUrl: string;
  /** Subtle CSS/canvas crop focal offset so frames across a roll feel distinct */
  cropFocus: { x: number; y: number; scale: number };
}

export type DrawerCategory = 'stills' | 'motion';

export interface FilmRoll {
  id: string;
  year: ArchiveYear;
  rollNumber: number;
  rollCode: string;
  title: string;
  filmStock: string;
  iso: number;
  location: string;
  month: string;
  frames: PhotoFrame[];
}

export interface MotionKeyframe {
  id: string;
  frameNumber: number;
  frameCode: string;
  timeSec: number;
  timecode: string;
  title: string;
  notes: string;
  imageUrl: string;
  cropFocus: { x: number; y: number; scale: number };
}

export interface MotionReel {
  id: string;
  year: ArchiveYear;
  reelNumber: number;
  reelCode: string;
  title: string;
  filmStock: string;
  format: string;
  fps: number;
  durationSec: number;
  durationLabel: string;
  camera: string;
  lens: string;
  location: string;
  month: string;
  notes: string;
  /** Optional real video file URL (.mp4/.webm); when omitted, renders smooth 24fps keyframe projection */
  videoUrl?: string;
  keyframes: MotionKeyframe[];
}

