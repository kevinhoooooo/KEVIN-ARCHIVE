function formatTimecode(sec: number): string {
  const s = Math.max(0, Math.floor(sec));
  const m = Math.floor(s / 60);
  const rem = s % 60;
  return `${String(m).padStart(2, '0')}:${String(rem).padStart(2, '0')}`;
}

export const MOTION_ARCHIVE_DATA: Record<ArchiveYear, MotionReel[]> = YEAR_CONFIGS.reduce(
  (acc, cfg) => {
    const year = cfg.year;
    const seeds = MOTION_SEEDS[year];

    acc[year] = seeds.map((seed, rIdx) => {
      const reelNum = rIdx + 1;
      const reelCode = `REEL ${String(reelNum).padStart(2, '0')}`;
      const kfCount = seed.keyframeTitles.length;
      const keyframes: MotionKeyframe[] = seed.keyframeTitles.map((kfTitle, kIdx) => {
        const frameNum = kIdx + 1;
        const timeSec = Math.round((kIdx / kfCount) * seed.durationSec);
        return {
          id: `${year}-M${reelNum}-K${frameNum}`,
          frameNumber: frameNum,
          frameCode: `${String(frameNum).padStart(2, '0')}M`,
          timeSec,
          timecode: formatTimecode(timeSec),
          title: kfTitle,
          notes: seed.notes,
          imageUrl: seed.images[kIdx % seed.images.length],
          cropFocus: CROP_PRESETS[(kIdx + rIdx) % CROP_PRESETS.length],
        };
      });

      return {
        id: `${year}-motion-${reelNum}`,
        year,
        reelNumber: reelNum,
        reelCode,
        title: seed.title,
        filmStock: seed.filmStock,
        format: seed.fps === 18 ? 'SUPER 8 · 18 FPS' : '16MM · 24 FPS',
        fps: seed.fps,
        durationSec: seed.durationSec,
        durationLabel: formatTimecode(seed.durationSec),
        camera: seed.camera,
        lens: seed.lens,
        location: seed.location,
        month: seed.month,
        notes: seed.notes,
        keyframes,
      };
    });

    return acc;
  },
  {} as Record<ArchiveYear, MotionReel[]>
);
